-- Coconut Boats upgrade: swappable engines, shared maintenance/to-do workflow,
-- system-aware pins, CSV-friendly boat codes, and engine hour tracking.
-- Run this in Supabase Dashboard > SQL Editor BEFORE deploying the replacement app.

begin;

-- 1) Human-readable boat identifier. Numeric id remains the internal PK/FK so this
-- migration does not break existing records, but boat_code is what the UI/CSV shows.
alter table public.boats add column if not exists boat_code text;

update public.boats
set boat_code = case
  when lower(name) = 'ka noelo kai' then 'KNK'
  when lower(name) = 'honu kai' then 'HK'
  when lower(name) = 'hinalea' then 'HIN'
  when lower(name) = 'loe' then 'LOE'
  when lower(name) ~ '^fleet boat[[:space:]]*[0-9]+' then
    'FB' || regexp_replace(lower(name), '^fleet boat[[:space:]]*([0-9]+).*$', '\1')
  else upper(left(regexp_replace(name, '[^A-Za-z0-9]+', '', 'g'), 8))
end
where boat_code is null or btrim(boat_code) = '';

-- Ensure any accidental duplicate fallback codes remain unique.
update public.boats b
set boat_code = b.boat_code || '-' || b.id
where exists (
  select 1 from public.boats x
  where x.boat_code = b.boat_code and x.id < b.id
);

alter table public.boats alter column boat_code set not null;
create unique index if not exists boats_boat_code_uidx on public.boats(boat_code);

-- 2) Boat maintenance pins now know which system they represent, allowing the
-- system filter to hide unrelated pins on the schematic.
alter table public.maintenance_pins add column if not exists system text not null default '';

-- Existing pins cannot be inferred perfectly. Give them a visible placeholder;
-- you can edit them later by recreating/moving them under the desired System.
update public.maintenance_pins set system = 'Unassigned' where btrim(system) = '';

-- 3) Normalize existing maintenance values to the new vocabulary.
update public.maintenance_records set category = 'Routine Maintenance' where category = 'Maintenance';
update public.maintenance_records set category = 'Observation' where category = 'Inspection';
update public.maintenance_records set status = 'Open Issue' where status in ('Open', 'Monitor');

-- Cost already exists in the current database, but this keeps the migration safe
-- for older copies of the project.
alter table public.maintenance_records add column if not exists cost numeric(12,2);

-- 4) Fold the old todos table into maintenance_records so To-Do becomes a filtered
-- view of maintenance instead of a second set of records that can drift out of sync.
do $$
begin
  if to_regclass('public.todos') is not null then
    insert into public.maintenance_records (
      boat_id, pin_id, title, item, description, system, category, status,
      date_created, due_date, notes, cost
    )
    select
      boat_id, pin_id, title, nullif(item, ''), null, system,
      case
        when category = 'Maintenance' then 'Routine Maintenance'
        when category = 'Inspection' then 'Observation'
        when category in ('Repair', 'Routine Maintenance', 'Observation', 'Admin') then category
        else 'Repair'
      end,
      case when status = 'Scheduled' then 'Scheduled' else 'Open Issue' end,
      created_at::date, due_date, coalesce(notes, ''), null
    from public.todos;

    drop table public.todos;
  end if;
end $$;

-- New vocabulary checks. Drop first so this file can be re-run after earlier experiments.
alter table public.maintenance_records drop constraint if exists maintenance_records_category_check;
alter table public.maintenance_records add constraint maintenance_records_category_check
  check (category in ('Repair', 'Routine Maintenance', 'Observation', 'Admin'));

alter table public.maintenance_records drop constraint if exists maintenance_records_status_check;
alter table public.maintenance_records add constraint maintenance_records_status_check
  check (status in ('Open Issue', 'Scheduled', 'Done'));

-- 5) Engines are independent assets. Changing boat_id/position in Supabase swaps an
-- engine to another boat without losing hours, schematic, pins, or maintenance history.
create table if not exists public.engines (
  id bigint generated by default as identity primary key,
  engine_code text not null unique,
  boat_id bigint references public.boats(id) on delete set null,
  position text not null default 'Single' check (position in ('Single', 'Port', 'Starboard', 'Other')),
  make text,
  model text,
  year text,
  serial_number text,
  horsepower numeric(7,2),
  engine_url text,
  schematic text,
  lifetime_hours numeric(10,1) not null default 0 check (lifetime_hours >= 0),
  service_hours numeric(10,1) not null default 0 check (service_hours >= 0),
  service_interval_hours numeric(10,1) not null default 90 check (service_interval_hours > 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists engines_boat_id_idx on public.engines(boat_id);

create table if not exists public.engine_pins (
  id bigint generated by default as identity primary key,
  engine_id bigint not null references public.engines(id) on delete cascade,
  x double precision not null check (x >= 0 and x <= 100),
  y double precision not null check (y >= 0 and y <= 100),
  name text not null default '',
  system text not null default 'Engine',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists engine_pins_engine_id_idx on public.engine_pins(engine_id);

create table if not exists public.engine_maintenance_records (
  id bigint generated by default as identity primary key,
  engine_id bigint not null references public.engines(id) on delete cascade,
  boat_id_at_time bigint references public.boats(id) on delete set null,
  pin_id bigint references public.engine_pins(id) on delete set null,
  title text not null,
  item text,
  description text,
  system text not null default 'Engine',
  category text not null default 'Repair'
    check (category in ('Repair', 'Routine Maintenance', 'Observation', 'Admin')),
  status text not null default 'Open Issue'
    check (status in ('Open Issue', 'Scheduled', 'Done')),
  date_created date not null default current_date,
  due_date date,
  completed_date date,
  completed_by text,
  work_order text,
  notes text not null default '',
  attachments text[] not null default '{}',
  cost numeric(12,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists engine_maintenance_engine_id_idx on public.engine_maintenance_records(engine_id);
create index if not exists engine_maintenance_due_date_idx on public.engine_maintenance_records(due_date);

-- 6) Public access matches the current app's existing no-login behavior.
alter table public.engines enable row level security;
alter table public.engine_pins enable row level security;
alter table public.engine_maintenance_records enable row level security;

drop policy if exists "public engines access" on public.engines;
create policy "public engines access" on public.engines for all to anon, authenticated using (true) with check (true);

drop policy if exists "public engine pins access" on public.engine_pins;
create policy "public engine pins access" on public.engine_pins for all to anon, authenticated using (true) with check (true);

drop policy if exists "public engine maintenance access" on public.engine_maintenance_records;
create policy "public engine maintenance access" on public.engine_maintenance_records for all to anon, authenticated using (true) with check (true);

commit;

