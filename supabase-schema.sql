-- CoconutBoats initial Supabase schema
-- Run this entire file in Supabase Dashboard > SQL Editor.

create table if not exists public.boats (
  id bigint generated by default as identity primary key,
  name text not null,
  nickname text,
  type text not null default 'Vessel',
  location text not null default 'Coconut Island',
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  sort_order integer not null default 0,
  make text,
  model text,
  year text,
  length text,
  hull_number text,
  registration text,
  engines text,
  engine_url text,
  fuel_capacity text,
  battery_type text,
  photo text,
  schematic text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.maintenance_pins (
  id bigint generated by default as identity primary key,
  boat_id bigint not null references public.boats(id) on delete cascade,
  x double precision not null check (x >= 0 and x <= 100),
  y double precision not null check (y >= 0 and y <= 100),
  name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.todos (
  id bigint generated by default as identity primary key,
  boat_id bigint not null references public.boats(id) on delete cascade,
  pin_id bigint references public.maintenance_pins(id) on delete set null,
  title text not null,
  system text not null default '',
  item text not null default '',
  category text not null default 'Repair',
  due_date date,
  status text not null default 'Open Issue',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.maintenance_records (
  id bigint generated by default as identity primary key,
  boat_id bigint not null references public.boats(id) on delete cascade,
  pin_id bigint references public.maintenance_pins(id) on delete set null,
  title text not null,
  item text,
  description text,
  system text not null default '',
  category text not null default 'Maintenance',
  status text not null default 'Done',
  date_created date not null default current_date,
  due_date date,
  completed_date date,
  completed_at timestamptz,
  completed_by text,
  work_order text,
  notes text not null default '',
  attachments text[] not null default '{}',
  cost numeric(12,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists boats_sort_order_idx on public.boats(sort_order, name);
create index if not exists todos_boat_id_idx on public.todos(boat_id);
create index if not exists todos_due_date_idx on public.todos(due_date);
create index if not exists maintenance_records_boat_id_idx on public.maintenance_records(boat_id);
create index if not exists maintenance_pins_boat_id_idx on public.maintenance_pins(boat_id);

